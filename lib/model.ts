// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol
// is pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol);
// the snapshot's live-token protocols are kept apart and shown as the market's own values, never
// mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. No protocol name is ever
// special-cased: the same function scores every row.
//
//   base         = tvl_usd x BASE_MULTIPLE            (0.25, see calibration below)
//   category     = live market multiple for the protocol's category, shrunk toward 1
//   chains       = 1 + 0.015 x min(chains, 10)         (multi-chain reach, capped at 1.15)
//   growth       = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied      = max(1, round(base x category x chains x growthMult x maturity))
//
// Calibration: BASE_MULTIPLE is not a guess. The snapshot's live-token protocols (the ones whose
// token already trades) carry both a TVL and a market cap, so the market's own multiple is
// median(mcap_usd / tvl_usd) across them. On this snapshot that median is about 0.24, which the model
// rounds to 0.25. The category factor is the same idea per category: median(mcap / TVL) of the
// live protocols in that category, divided by the global median, shrunk toward 1 by the
// category's sample size (n / (n + 5)) and clamped to [0.6, 1.6]. A category with fewer than 3
// live protocols, or none at all, gets a factor of 1. The calibration is recomputed from the
// snapshot on every run, so the model follows the data, never a hand-written list.

